// aliases.go carries the curated knowledge needed to reconcile the wildly
// inconsistent club naming across the five match datasets.
//
// Three tables are used, in increasing order of generality:
//
//   - rawNameOverrides — exact full-name fixes, for names whose trailing token
//     looks like a state code but is not ("Central SC" is Central Sport Club of
//     Pernambuco, "River AC" is River Atlético Clube of Piauí).
//   - baseAliases      — slug rewrites plus a *default* region, applied only
//     when the source omitted the region ("Atletico Mineiro" → atletico/MG,
//     bare "Flamengo" → flamengo/RJ).
//   - canonicalDisplay — pretty, correctly accented display names per team ID.
package soccer

