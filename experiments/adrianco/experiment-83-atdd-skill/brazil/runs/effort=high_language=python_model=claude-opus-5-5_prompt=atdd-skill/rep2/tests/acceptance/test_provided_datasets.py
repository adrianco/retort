"""
Executable specifications: answering questions from the provided Kaggle datasets.

Capability: every provided CSV file is loaded and queryable, well-known facts
about Brazilian football come out right, and the sample questions from the
specification are answered quickly (simple lookups < 2s, aggregates < 5s).

Unlike the other specs, these run against the real data in data/kaggle rather
than synthetic data generated by the test, so they share one read-only server.

Layer: test case (layer 1 of the four-layer model).
"""
import pytest


def test_should_load_every_provided_dataset(provided):
    provided.confirm_datasets_loaded({
        "brasileirão": 4180,
        "copa do brasil": 1337,
        "libertadores": 1255,
        "extended statistics": 10296,
        "historical brasileirão": 6886,
        "fifa players": 18207,
    })


def test_should_know_flamengo_won_the_2019_brasileirao_with_90_points(provided):
    provided.competitions.confirm_standing(2019, position=1, team="Flamengo", points=90, won=28, drawn=6, lost=4)


def test_should_know_who_was_relegated_in_2020(provided):
    provided.competitions.confirm_relegated(2020, ["Vasco", "Goiás", "Coritiba", "Botafogo"])


def test_should_know_neymar_is_the_top_rated_brazilian_player(provided):
    provided.players.confirm_top_players(nationality="Brazil", ranked=["Neymar Jr"])


def test_should_combine_fla_flu_meetings_from_several_datasets(provided):
    provided.matches.confirm_meetings("Flamengo", "Fluminense", from_competitions=[
        "Brasileirão Série A", "Copa do Brasil"], at_least=40)


SIMPLE_LOOKUPS = {
    "Show me all Flamengo vs Fluminense matches": lambda s: s.matches.meetings("Flamengo", "Fluminense"),
    "What matches did Palmeiras play in 2022?": lambda s: s.matches.team_played("Palmeiras", season=2022),
    "Find all Copa do Brasil finals": lambda s: s.matches.find(competition="Copa do Brasil", stage="final"),
    "When did Flamengo last play Corinthians?": lambda s: s.matches.last_meeting("Flamengo", "Corinthians"),
    "Who is Gabriel Barbosa?": lambda s: s.players.profile("Gabriel Barbosa"),
    "Which players play for Grêmio?": lambda s: s.players.top(club="Grêmio"),
    "Show me all forwards from Santos": lambda s: s.players.top(club="Santos", position="forward"),
    "Find all Brazilian players in the dataset": lambda s: s.players.top(nationality="Brazil"),
    "Who are the highest-rated players at Cruzeiro?": lambda s: s.players.top(club="Cruzeiro"),
    "What competitions has Palmeiras played in?": lambda s: s.teams.competitions("Palmeiras"),
    "What does the dataset know about Atlético Mineiro?": lambda s: s.teams.club_profile("Atlético Mineiro"),
}

AGGREGATE_QUERIES = {
    "What is Corinthians' home record in 2022?":
        lambda s: s.teams.record("Corinthians", season=2022, venue="home"),
    "Which team scored the most goals in Serie A 2022?": lambda s: s.competitions.top_scoring_teams(2022),
    "Compare Palmeiras and Santos head-to-head": lambda s: s.teams.head_to_head("Palmeiras", "Santos"),
    "Who won the 2019 Brasileirão?": lambda s: s.competitions.table(2019),
    "Show the 2018 Copa Libertadores bracket": lambda s: s.competitions.bracket("Libertadores", 2018),
    "Which teams were relegated in 2020?": lambda s: s.competitions.table(2020),
    "What's the average goals per match in the Brasileirão?":
        lambda s: s.stats.summary(competition="Brasileirão"),
    "Which team has the best away record?": lambda s: s.stats.best_records(venue="away"),
    "Which team has the best home record?": lambda s: s.stats.best_records(venue="home"),
    "Show me the biggest wins in the dataset": lambda s: s.stats.biggest_wins(),
    "Compare the 2018 and 2019 seasons": lambda s: s.stats.compare_seasons(2018, 2019),
    "Show me all derbies in 2022": lambda s: s.stats.derbies(2022),
    "Brazilian players at Brazilian clubs": lambda s: s.players.brazilians_at_brazilian_clubs(),
}


@pytest.mark.parametrize("question", SIMPLE_LOOKUPS)
def test_should_answer_simple_lookups_within_two_seconds(provided, question):
    provided.confirm_answered(question, SIMPLE_LOOKUPS[question], within_seconds=2)


@pytest.mark.parametrize("question", AGGREGATE_QUERIES)
def test_should_answer_aggregate_questions_within_five_seconds(provided, question):
    provided.confirm_answered(question, AGGREGATE_QUERIES[question], within_seconds=5)
