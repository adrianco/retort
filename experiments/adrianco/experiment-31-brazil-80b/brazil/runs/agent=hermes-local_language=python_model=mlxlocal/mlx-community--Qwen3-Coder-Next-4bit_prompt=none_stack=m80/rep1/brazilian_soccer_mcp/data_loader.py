"""
Brazilian Soccer MCP Server - Data Loader module.

This module loads and preprocesses all CSV data files for the Brazilian soccer MCP server.
It handles:
- Loading match data from multiple sources
- Loading player data from FIFA database
- Normalizing team names across different datasets
- Handling date format variations
"""

import os
import pandas as pd
from typing import Dict, Optional, List, Any
from datetime import datetime


class DataLoader:
    """
    Loads and preprocesses Brazilian soccer data from CSV files.
    
    Handles multiple date formats, team name variations, and normalizes
    data structures for consistent querying.
    """
    
    def __init__(self, data_dir: str = "data/kaggle"):
        """
        Initialize the DataLoader with the path to data files.
        
        Args:
            data_dir: Path to directory containing CSV data files
        """
        self.data_dir = data_dir
        self.data: Dict[str, pd.DataFrame] = {}
        self._load_all_data()
    
    def _get_csv_path(self, filename: str) -> str:
        """Get full path to a CSV file."""
        return os.path.join(self.data_dir, filename)
    
    def _normalize_team_name(self, team: str) -> str:
        """
        Normalize team names for consistent matching.
        
        Removes state suffixes and special characters for normalization.
        
        Args:
            team: Raw team name
            
        Returns:
            Normalized team name
        """
        if not isinstance(team, str):
            return str(team) if team else ""
        
        # Remove state suffix like -SP, -RJ, -PE, etc.
        import re
        normalized = re.sub(r'-[A-Z]{2}$', '', team)
        # Remove parentheses with country info like (URU), (ARG)
        normalized = re.sub(r'\s*\([^)]+\)$', '', normalized)
        # Strip whitespace
        normalized = normalized.strip()
        return normalized
    
    def _parse_date(self, date_str: str) -> Optional[datetime]:
        """
        Parse date strings in multiple formats.
        
        Handles:
        - ISO format: 2023-09-24
        - Brazilian format: 29/03/2003
        - With time: 2012-05-19 18:30:00
        
        Args:
            date_str: Date string to parse
            
        Returns:
            datetime object or None if parsing fails
        """
        if pd.isna(date_str):
            return None
        
        date_str = str(date_str).strip()
        
        formats = [
            "%Y-%m-%d %H:%M:%S",
            "%Y-%m-%d",
            "%d/%m/%Y",
            "%d/%m/%Y %H:%M:%S",
        ]
        
        for fmt in formats:
            try:
                return datetime.strptime(date_str, fmt)
            except ValueError:
                continue
        
        return None
    
    def load_brasileirao(self) -> pd.DataFrame:
        """
        Load Brasileirão Serie A matches data.
        
        Returns:
            DataFrame with match data
        """
        path = self._get_csv_path("Brasileirao_Matches.csv")
        df = pd.read_csv(path)
        
        # Parse datetime
        df['datetime'] = pd.to_datetime(df['datetime'], errors='coerce')
        
        # Normalize team names
        df['home_team_normalized'] = df['home_team'].apply(self._normalize_team_name)
        df['away_team_normalized'] = df['away_team'].apply(self._normalize_team_name)
        
        # Handle NaN season values - use Int64 nullable integer type
        df['season'] = df['season'].astype('Int64')
        df['round'] = df['round'].astype(int)
        
        self.data['brasileirao'] = df
        return df
    
    def load_brazilian_cup(self) -> pd.DataFrame:
        """
        Load Copa do Brasil matches data.
        
        Returns:
            DataFrame with match data
        """
        path = self._get_csv_path("Brazilian_Cup_Matches.csv")
        df = pd.read_csv(path)
        
        # Parse datetime
        df['datetime'] = pd.to_datetime(df['datetime'], errors='coerce')
        
        # Normalize team names
        df['home_team_normalized'] = df['home_team'].apply(self._normalize_team_name)
        df['away_team_normalized'] = df['away_team'].apply(self._normalize_team_name)
        
        # Handle NaN season values - use Int64 nullable integer type
        df['season'] = df['season'].astype('Int64')
        
        self.data['brazilian_cup'] = df
        return df
    
    def load_libertadores(self) -> pd.DataFrame:
        """
        Load Copa Libertadores matches data.
        
        Returns:
            DataFrame with match data
        """
        path = self._get_csv_path("Libertadores_Matches.csv")
        df = pd.read_csv(path)
        
        # Parse datetime
        df['datetime'] = pd.to_datetime(df['datetime'], errors='coerce')
        
        # Normalize team names
        df['home_team_normalized'] = df['home_team'].apply(self._normalize_team_name)
        df['away_team_normalized'] = df['away_team'].apply(self._normalize_team_name)
        
        # Handle NaN season values - use Int64 nullable integer type
        df['season'] = df['season'].astype('Int64')
        
        self.data['libertadores'] = df
        return df
    
    def load_br_football(self) -> pd.DataFrame:
        """
        Load BR-Football-Dataset with extended match statistics.
        
        Returns:
            DataFrame with match data
        """
        path = self._get_csv_path("BR-Football-Dataset.csv")
        df = pd.read_csv(path)
        
        # Parse date
        df['date'] = pd.to_datetime(df['date'], errors='coerce')
        
        # Normalize team names
        df['home_normalized'] = df['home'].apply(self._normalize_team_name)
        df['away_normalized'] = df['away'].apply(self._normalize_team_name)
        
        self.data['br_football'] = df
        return df
    
    def load_historical_brasileirao(self) -> pd.DataFrame:
        """
        Load historical Brasileirão data (2003-2019).
        
        Returns:
            DataFrame with match data
        """
        path = self._get_csv_path("novo_campeonato_brasileiro.csv")
        df = pd.read_csv(path)
        
        # Parse date in Brazilian format
        df['Data_parsed'] = df['Data'].apply(self._parse_date)
        
        # Normalize team names
        df['Equipe_mandante_normalized'] = df['Equipe_mandante'].apply(self._normalize_team_name)
        df['Equipe_visitante_normalized'] = df['Equipe_visitante'].apply(self._normalize_team_name)
        
        df['Ano'] = df['Ano'].astype(int)
        df['Rodada'] = df['Rodada'].astype(int)
        
        self.data['historical_brasileirao'] = df
        return df
    
    def load_fifa_players(self) -> pd.DataFrame:
        """
        Load FIFA player database.
        
        Returns:
            DataFrame with player data
        """
        path = self._get_csv_path("fifa_data.csv")
        df = pd.read_csv(path)
        
        # Clean up column names (remove leading spaces)
        df.columns = df.columns.str.strip()
        
        # Filter out unnamed columns if they exist
        df = df[[col for col in df.columns if not col.startswith('Unnamed')]]
        
        self.data['fifa_players'] = df
        return df
    
    def _load_all_data(self):
        """Load all data files."""
        print("Loading Brazilian soccer data...")
        
        self.load_brasileirao()
        print(f"  - Brasileirão: {len(self.data['brasileirao'])} matches")
        
        self.load_brazilian_cup()
        print(f"  - Copa do Brasil: {len(self.data['brazilian_cup'])} matches")
        
        self.load_libertadores()
        print(f"  - Libertadores: {len(self.data['libertadores'])} matches")
        
        self.load_br_football()
        print(f"  - BR Football: {len(self.data['br_football'])} matches")
        
        self.load_historical_brasileirao()
        print(f"  - Historical Brasileirão: {len(self.data['historical_brasileirao'])} matches")
        
        self.load_fifa_players()
        print(f"  - FIFA Players: {len(self.data['fifa_players'])} players")
        
        print(f"Total matches loaded: {sum(len(df) for key, df in self.data.items() if 'player' not in key)}")
        print("Data loading complete.\n")
    
    def get_data(self, key: str) -> pd.DataFrame:
        """Get a specific dataset by key."""
        return self.data.get(key)
    
    def get_all_matches(self) -> pd.DataFrame:
        """
        Combine all match data into a single DataFrame.
        
        Returns:
            DataFrame with all matches from all sources
        """
        matches = []
        
        # Brasileirão
        df = self.data['brasileirao'].copy()
        df['competition'] = 'Brasileirão'
        matches.append(df)
        
        # Copa do Brasil
        df = self.data['brazilian_cup'].copy()
        df['competition'] = 'Copa do Brasil'
        matches.append(df)
        
        # Libertadores
        df = self.data['libertadores'].copy()
        df['competition'] = 'Copa Libertadores'
        matches.append(df)
        
        # BR Football
        df = self.data['br_football'].copy()
        df['competition'] = df['tournament']
        matches.append(df)
        
        # Historical Brasileirão
        df = self.data['historical_brasileirao'].copy()
        df['competition'] = 'Brasileirão'
        df['datetime'] = df['Data_parsed']
        df['home_team'] = df['Equipe_mandante']
        df['away_team'] = df['Equipe_visitante']
        df['home_team_normalized'] = df['Equipe_mandante_normalized']
        df['away_team_normalized'] = df['Equipe_visitante_normalized']
        df['home_goal'] = df['Gols_mandante']
        df['away_goal'] = df['Gols_visitante']
        df['season'] = df['Ano']
        df['round'] = df['Rodada']
        matches.append(df)
        
        return pd.concat(matches, ignore_index=True)
    
    def get_all_players(self) -> pd.DataFrame:
        """Get all player data."""
        return self.data.get('fifa_players')


# Singleton instance
_loader_instance: Optional[DataLoader] = None


def get_data_loader(data_dir: str = "data/kaggle") -> DataLoader:
    """
    Get or create the singleton DataLoader instance.
    
    Args:
        data_dir: Path to data directory
        
    Returns:
        DataLoader instance
    """
    global _loader_instance
    if _loader_instance is None:
        _loader_instance = DataLoader(data_dir)
    return _loader_instance


