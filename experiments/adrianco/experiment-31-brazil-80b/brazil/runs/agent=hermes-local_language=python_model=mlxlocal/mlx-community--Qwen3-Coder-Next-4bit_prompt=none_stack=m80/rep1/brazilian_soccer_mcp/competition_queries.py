from typing import Dict, List, Any, Optional
import pandas as pd
from collections import defaultdict


class CompetitionQueryHandler:
    """
    Handles competition-related queries for the Brazilian Soccer MCP Server.
    
    Provides methods to calculate standings, get match schedules,
    and analyze competition statistics.
    """
    
    def __init__(self, data_loader, match_handler):
        """
        Initialize the CompetitionQueryHandler.
        
        Args:
            data_loader: DataLoader instance
            match_handler: MatchQueryHandler instance
        """
        self.data_loader = data_loader
        self.match_handler = match_handler
        self.all_matches = data_loader.get_all_matches()
    
    def calculate_standings(
        self, 
        season: int, 
        competition: Optional[str] = None
    ) -> pd.DataFrame:
        """
        Calculate league standings for a season.
        
        Args:
            season: Season year
            competition: Optional competition filter
            
        Returns:
            DataFrame with standings
        """
        # Filter matches by season
        matches = self.match_handler.get_matches_by_season(season)
        
        if competition:
            matches = matches[matches['competition'].str.lower().str.contains(competition.lower())]
        
        if len(matches) == 0:
            return pd.DataFrame()
        
        # Initialize team standings
        standings = defaultdict(lambda: {
            'team': '',
            'played': 0,
            'won': 0,
            'drawn': 0,
            'lost': 0,
            'goals_for': 0,
            'goals_against': 0,
            'goal_difference': 0,
            'points': 0
        })
        
        # Process each match
        for _, match in matches.iterrows():
            home_team = match['home_team_normalized']
            away_team = match['away_team_normalized']
            home_goal = int(match['home_goal']) if pd.notna(match['home_goal']) else 0
            away_goal = int(match['away_goal']) if pd.notna(match['away_goal']) else 0
            
            # Update home team
            standings[home_team]['team'] = match['home_team']
            standings[home_team]['played'] += 1
            standings[home_team]['goals_for'] += home_goal
            standings[home_team]['goals_against'] += away_goal
            standings[home_team]['goal_difference'] += (home_goal - away_goal)
            
            # Update away team
            standings[away_team]['team'] = match['away_team']
            standings[away_team]['played'] += 1
            standings[away_team]['goals_for'] += away_goal
            standings[away_team]['goals_against'] += home_goal
            standings[away_team]['goal_difference'] += (away_goal - home_goal)
            
            # Determine winner
            if home_goal > away_goal:
                standings[home_team]['won'] += 1
                standings[home_team]['points'] += 3
                standings[away_team]['lost'] += 1
            elif home_goal < away_goal:
                standings[away_team]['won'] += 1
                standings[away_team]['points'] += 3
                standings[home_team]['lost'] += 1
            else:
                standings[home_team]['drawn'] += 1
                standings[away_team]['drawn'] += 1
                standings[home_team]['points'] += 1
                standings[away_team]['points'] += 1
        
        # Convert to DataFrame
        df = pd.DataFrame(list(standings.values()))
        
        # Sort by points, then goal difference, then goals scored
        df = df.sort_values(
            by=['points', 'goal_difference', 'goals_for', 'won'],
            ascending=[False, False, False, False]
        ).reset_index(drop=True)
        
        # Add position column
        df.insert(0, 'position', range(1, len(df) + 1))
        
        return df
    
    def get_competition_standings(
        self,
        competition: str,
        season: int
    ) -> pd.DataFrame:
        """
        Get standings for a specific competition and season.
        
        Args:
            competition: Competition name
            season: Season year
            
        Returns:
            DataFrame with standings
        """
        return self.calculate_standings(season, competition)
    
    def get_relegation_zones(self, season: int, competition: str = "Brasileirão") -> pd.DataFrame:
        """
        Get teams in relegation zones for a season.
        
        Args:
            season: Season year
            competition: Competition name
            
        Returns:
            DataFrame with relegated teams
        """
        standings = self.calculate_standings(season, competition)
        
        if len(standings) < 4:
            return standings
        
        # Get bottom 4 teams (relegation zone in Brasileirão)
        relegated = standings.tail(4)
        return relegated
    
    def get_champion(self, season: int, competition: str = "Brasileirão") -> Optional[Dict[str, Any]]:
        """
        Get the champion of a competition for a season.
        
        Args:
            season: Season year
            competition: Competition name
            
        Returns:
            Dictionary with champion info or None
        """
        standings = self.calculate_standings(season, competition)
        
        if len(standings) == 0:
            return None
        
        champion = standings.iloc[0]
        
        return {
            'position': int(champion['position']),
            'team': champion['team'],
            'points': int(champion['points']),
            'played': int(champion['played']),
            'won': int(champion['won']),
            'drawn': int(champion['drawn']),
            'lost': int(champion['lost']),
            'goals_for': int(champion['goals_for']),
            'goals_against': int(champion['goals_against']),
            'goal_difference': int(champion['goal_difference'])
        }
    
    def get_competition_matches(
        self,
        competition: str,
        season: Optional[int] = None
    ) -> pd.DataFrame:
        """
        Get all matches for a competition.
        
        Args:
            competition: Competition name
            season: Optional season filter
            
        Returns:
            DataFrame with matches
        """
        matches = self.match_handler.find_matches_by_competition(competition)
        
        if season:
            matches = matches[matches['season'] == season]
        
        return matches
    
    def get_competition_seasons(self, competition: str) -> List[int]:
        """
        Get all seasons a competition was played.
        
        Args:
            competition: Competition name
            
        Returns:
            List of season years
        """
        return self.match_handler.get_competition_seasons(competition)
    
    def get_cup_bracket(self, competition: str, season: int) -> Dict[str, Any]:
        """
        Get cup bracket information for a season.
        
        Note: This provides a simplified view as the raw data doesn't
        contain full bracket information.
        
        Args:
            competition: Cup competition name
            season: Season year
            
        Returns:
            Dictionary with cup bracket info
        """
        matches = self.get_competition_matches(competition, season)
        
        if len(matches) == 0:
            return {'error': f"No matches found for {competition} {season}"}
        
        # Get unique rounds/stages
        rounds = sorted(matches['round'].unique().tolist()) if 'round' in matches.columns else []
        
        # Get stage information if available
        stages = []
        if 'stage' in matches.columns:
            stages = matches['stage'].dropna().unique().tolist()
        
        # Get final match
        final_match = None
        if 'round' in matches.columns:
            final_round = max(matches['round'].dropna().unique()) if len(matches['round'].dropna()) > 0 else None
            if final_round is not None:
                final_matches = matches[matches['round'] == final_round]
                if len(final_matches) > 0:
                    final_match = final_matches.iloc[0]
        
        return {
            'competition': competition,
            'season': season,
            'total_matches': len(matches),
            'rounds': rounds[-5:] if len(rounds) > 5 else rounds,  # Last 5 rounds
            'stages': stages,
            'final_match': {
                'home_team': final_match['home_team'] if final_match is not None else None,
                'away_team': final_match['away_team'] if final_match is not None else None,
                'home_goal': int(final_match['home_goal']) if final_match is not None and pd.notna(final_match['home_goal']) else None,
                'away_goal': int(final_match['away_goal']) if final_match is not None and pd.notna(final_match['away_goal']) else None,
                'datetime': str(final_match['datetime']) if final_match is not None and pd.notna(final_match['datetime']) else None
            } if final_match is not None else None
        }
    
    def get_top_scorers_in_season(self, season: int, competition: Optional[str] = None, limit: int = 10) -> List[Dict[str, Any]]:
        """
        Get top scorers for a season.
        
        Note: The provided match data doesn't include individual scorer data.
        This returns a placeholder response indicating the limitation.
        
        Args:
            season: Season year
            competition: Optional competition filter
            limit: Number of top scorers to return
            
        Returns:
            List of top scorers (with placeholder info)
        """
        # The match data doesn't include individual scorer information
        # This is a limitation of the provided datasets
        return [
            {
                'name': 'Top scorer data not available in match datasets',
                'team': 'N/A',
                'goals': 'N/A',
                'note': 'Individual scorer data is not included in the provided match datasets. Player statistics are available in the FIFA database.'
            }
        ]
    
    def get_biggest_victories(self, competition: Optional[str] = None, limit: int = 10) -> List[Dict[str, Any]]:
        """
        Get the biggest victories in a competition.
        
        Args:
            competition: Optional competition filter
            limit: Number of results
            
        Returns:
            List of biggest victories
        """
        matches = self.all_matches.copy()
        
        if competition:
            matches = matches[matches['competition'].str.lower().str.contains(competition.lower())]
        
        # Calculate goal difference
        matches = matches.copy()
        matches['goal_diff'] = (matches['home_goal'].fillna(0).astype(int) - matches['away_goal'].fillna(0).astype(int)).abs()
        
        # Sort by goal difference
        biggest = matches.nlargest(limit, 'goal_diff')
        
        result = []
        for _, match in biggest.iterrows():
            result.append({
                'date': str(match['datetime']) if pd.notna(match['datetime']) else None,
                'home_team': match['home_team'],
                'away_team': match['away_team'],
                'home_goal': int(match['home_goal']) if pd.notna(match['home_goal']) else 0,
                'away_goal': int(match['away_goal']) if pd.notna(match['away_goal']) else 0,
                'goal_difference': int(match['goal_diff']),
                'competition': match['competition'],
                'season': int(match['season']) if pd.notna(match['season']) else None
            })
        
        return result
    
    def get_competition_summary(self, competition: str, season: Optional[int] = None) -> Dict[str, Any]:
        """
        Get a summary of a competition.
        
        Args:
            competition: Competition name
            season: Optional season filter
            
        Returns:
            Dictionary with competition summary
        """
        matches = self.get_competition_matches(competition, season)
        
        if len(matches) == 0:
            return {'error': f"No matches found for {competition}"}
        
        # Basic statistics
        total_matches = len(matches)
        total_goals = int(matches['home_goal'].sum()) + int(matches['away_goal'].sum())
        avg_goals = round(total_goals / total_matches, 2) if total_matches > 0 else 0
        
        # Home vs away wins
        home_wins = 0
        away_wins = 0
        draws = 0
        
        for _, match in matches.iterrows():
            home_goal = int(match['home_goal']) if pd.notna(match['home_goal']) else 0
            away_goal = int(match['away_goal']) if pd.notna(match['away_goal']) else 0
            
            if home_goal > away_goal:
                home_wins += 1
            elif away_goal > home_goal:
                away_wins += 1
            else:
                draws += 1
        
        # Teams participated
        teams = set()
        for _, match in matches.iterrows():
            teams.add(match['home_team_normalized'])
            teams.add(match['away_team_normalized'])
        
        return {
            'competition': competition,
            'season': season,
            'total_matches': total_matches,
            'total_goals': total_goals,
            'average_goals_per_match': avg_goals,
            'home_wins': home_wins,
            'away_wins': away_wins,
            'draws': draws,
            'home_win_rate': round(home_wins / total_matches * 100, 1) if total_matches > 0 else 0,
            'teams_participated': len(teams)
        }


