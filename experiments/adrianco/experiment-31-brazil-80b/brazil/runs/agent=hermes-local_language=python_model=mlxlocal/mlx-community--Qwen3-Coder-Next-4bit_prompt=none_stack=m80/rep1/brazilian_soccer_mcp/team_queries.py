from typing import Dict, List, Any, Optional
import pandas as pd
from collections import defaultdict


class TeamQueryHandler:
    """
    Handles team-related queries and statistics for the Brazilian Soccer MCP Server.
    
    Provides methods to analyze team performance, calculate statistics,
    and compare teams head-to-head.
    """
    
    def __init__(self, data_loader, match_handler):
        """
        Initialize the TeamQueryHandler.
        
        Args:
            data_loader: DataLoader instance
            match_handler: MatchQueryHandler instance
        """
        self.data_loader = data_loader
        self.match_handler = match_handler
        self.all_matches = data_loader.get_all_matches()
    
    def _get_team_stats(self, team_name: str, matches: pd.DataFrame) -> Dict[str, Any]:
        """
        Calculate statistics for a team from a set of matches.
        
        Args:
            team_name: Team name to calculate stats for
            matches: DataFrame with matches
            
        Returns:
            Dictionary with team statistics
        """
        team_normalized = self.data_loader._normalize_team_name(team_name)
        
        # Filter matches for this team
        team_matches = matches[
            (matches['home_team_normalized'] == team_normalized) |
            (matches['away_team_normalized'] == team_normalized)
        ]
        
        if len(team_matches) == 0:
            return {
                'team': team_name,
                'matches': 0,
                'wins': 0,
                'draws': 0,
                'losses': 0,
                'goals_for': 0,
                'goals_against': 0,
                'points': 0,
                'win_rate': 0.0
            }
        
        stats = {
            'team': team_name,
            'matches': len(team_matches),
            'wins': 0,
            'draws': 0,
            'losses': 0,
            'goals_for': 0,
            'goals_against': 0,
            'points': 0,
            'win_rate': 0.0
        }
        
        for _, match in team_matches.iterrows():
            home_team = match['home_team_normalized']
            away_team = match['away_team_normalized']
            home_goal = int(match['home_goal']) if pd.notna(match['home_goal']) else 0
            away_goal = int(match['away_goal']) if pd.notna(match['away_goal']) else 0
            
            if home_team == team_normalized:
                stats['goals_for'] += home_goal
                stats['goals_against'] += away_goal
                
                if home_goal > away_goal:
                    stats['wins'] += 1
                    stats['points'] += 3
                elif home_goal == away_goal:
                    stats['draws'] += 1
                    stats['points'] += 1
                else:
                    stats['losses'] += 1
            else:
                stats['goals_for'] += away_goal
                stats['goals_against'] += home_goal
                
                if away_goal > home_goal:
                    stats['wins'] += 1
                    stats['points'] += 3
                elif away_goal == home_goal:
                    stats['draws'] += 1
                    stats['points'] += 1
                else:
                    stats['losses'] += 1
        
        stats['win_rate'] = round(stats['wins'] / stats['matches'] * 100, 1) if stats['matches'] > 0 else 0.0
        
        return stats
    
    def get_team_statistics(
        self,
        team_name: str,
        season: Optional[int] = None,
        competition: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Get comprehensive statistics for a team.
        
        Args:
            team_name: Team name
            season: Optional season filter
            competition: Optional competition filter
            
        Returns:
            Dictionary with team statistics
        """
        matches = self.all_matches.copy()
        
        if season:
            matches = matches[matches['season'] == season]
        
        if competition:
            matches = matches[matches['competition'].str.lower().str.contains(competition.lower())]
        
        return self._get_team_stats(team_name, matches)
    
    def get_home_away_stats(self, team_name: str, season: Optional[int] = None) -> Dict[str, Any]:
        """
        Get home and away statistics separately.
        
        Args:
            team_name: Team name
            season: Optional season filter
            
        Returns:
            Dictionary with home and away stats
        """
        team_normalized = self.data_loader._normalize_team_name(team_name)
        matches = self.all_matches.copy()
        
        if season:
            matches = matches[matches['season'] == season]
        
        home_matches = matches[matches['home_team_normalized'] == team_normalized]
        away_matches = matches[matches['away_team_normalized'] == team_normalized]
        
        home_stats = self._get_team_stats(team_name, home_matches)
        away_stats = self._get_team_stats(team_name, away_matches)
        
        return {
            'team': team_name,
            'season': season,
            'home': home_stats,
            'away': away_stats
        }
    
    def get_head_to_head(self, team1: str, team2: str) -> Dict[str, Any]:
        """
        Get head-to-head statistics between two teams.
        
        Args:
            team1: First team name
            team2: Second team name
            
        Returns:
            Dictionary with head-to-head data
        """
        matches = self.match_handler.find_match_by_teams(team1, team2)
        
        team1_normalized = self.data_loader._normalize_team_name(team1)
        team2_normalized = self.data_loader._normalize_team_name(team2)
        
        stats = {
            'team1': team1,
            'team2': team2,
            'total_matches': len(matches),
            'team1_wins': 0,
            'team2_wins': 0,
            'draws': 0,
            'team1_goals': 0,
            'team2_goals': 0,
            'recent_matches': []
        }
        
        for _, match in matches.iterrows():
            home_team = match['home_team_normalized']
            away_team = match['away_team_normalized']
            home_goal = int(match['home_goal']) if pd.notna(match['home_goal']) else 0
            away_goal = int(match['away_goal']) if pd.notna(match['away_goal']) else 0
            
            if home_team == team1_normalized:
                stats['team1_goals'] += home_goal
                stats['team2_goals'] += away_goal
                
                if home_goal > away_goal:
                    stats['team1_wins'] += 1
                elif away_goal > home_goal:
                    stats['team2_wins'] += 1
                else:
                    stats['draws'] += 1
            else:
                stats['team1_goals'] += away_goal
                stats['team2_goals'] += home_goal
                
                if away_goal > home_goal:
                    stats['team1_wins'] += 1
                elif home_goal > away_goal:
                    stats['team2_wins'] += 1
                else:
                    stats['draws'] += 1
            
            stats['recent_matches'].append({
                'date': str(match['datetime']) if pd.notna(match['datetime']) else None,
                'score': f"{home_goal}-{away_goal}",
                'competition': match['competition'],
                'season': int(match['season']) if pd.notna(match['season']) else None
            })
        
        # Sort recent matches by date descending
        stats['recent_matches'].sort(key=lambda x: x['date'] or '', reverse=True)
        
        return stats
    
    def get_team_competition_history(self, team_name: str, competition: str) -> Dict[str, Any]:
        """
        Get a team's history in a specific competition.
        
        Args:
            team_name: Team name
            competition: Competition name
            
        Returns:
            Dictionary with competition history
        """
        matches = self.match_handler.find_matches_by_team(
            team_name, 
            competition=competition
        )
        
        stats = self._get_team_stats(team_name, matches)
        stats['competition'] = competition
        stats['seasons_participated'] = sorted(matches['season'].unique().tolist())
        
        return stats
    
    def get_team_top_scorers(self, team_name: str, limit: int = 10) -> List[Dict[str, Any]]:
        """
        Get top scorers for a team (if player data is available).
        
        Note: This requires linking player data to match data which isn't
        directly available in the provided datasets. Returns placeholder.
        
        Args:
            team_name: Team name
            limit: Number of top scorers to return
            
        Returns:
            List of player statistics
        """
        # Player data is in FIFA database but not linked to match data
        # This would require additional data linking
        players_df = self.data_loader.get_data('fifa_players')
        
        if players_df is None:
            return []
        
        # Find players who play for the team
        team_normalized = self.data_loader._normalize_team_name(team_name)
        
        # Search for team in club names
        team_players = players_df[
            players_df['Club'].str.contains(team_name, case=False, na=False)
        ]
        
        if len(team_players) == 0:
            return []
        
        # Sort by overall rating
        top_players = team_players.nlargest(limit, 'Overall')
        
        result = []
        for _, player in top_players.iterrows():
            result.append({
                'name': player['Name'],
                'position': player.get('Position', 'N/A'),
                'overall': int(player['Overall']) if pd.notna(player['Overall']) else 0,
                'nationality': player.get('Nationality', 'N/A')
            })
        
        return result
    
    def get_team_performance_trend(self, team_name: str, season: Optional[int] = None) -> pd.DataFrame:
        """
        Get a team's performance trend over time.
        
        Args:
            team_name: Team name
            season: Optional season filter
            
        Returns:
            DataFrame with match results over time
        """
        matches = self.match_handler.find_matches_by_team(team_name)
        
        if season:
            matches = matches[matches['season'] == season]
        
        if len(matches) == 0:
            return matches
        
        # Sort by date
        matches = matches.sort_values('datetime')
        
        # Add result column
        results = []
        for _, match in matches.iterrows():
            home_team = match['home_team_normalized']
            away_team = match['away_team_normalized']
            home_goal = int(match['home_goal']) if pd.notna(match['home_goal']) else 0
            away_goal = int(match['away_goal']) if pd.notna(match['away_goal']) else 0
            
            team_normalized = self.data_loader._normalize_team_name(team_name)
            
            if home_team == team_normalized:
                if home_goal > away_goal:
                    result = 'W'
                elif home_goal == away_goal:
                    result = 'D'
                else:
                    result = 'L'
            else:
                if away_goal > home_goal:
                    result = 'W'
                elif away_goal == home_goal:
                    result = 'D'
                else:
                    result = 'L'
            
            results.append(result)
        
        matches = matches.copy()
        matches['result'] = results
        
        return matches[['datetime', 'competition', 'home_team', 'away_team', 'result', 'season']]
    
    def get_all_teams(self) -> List[str]:
        """
        Get list of all teams in the dataset.
        
        Returns:
            List of team names
        """
        teams = set()
        
        # From Brasileirão data
        df = self.data_loader.get_data('brasileirao')
        if df is not None:
            teams.update(df['home_team'].unique())
            teams.update(df['away_team'].unique())
        
        # From other match data
        for key in ['brazilian_cup', 'libertadores', 'br_football', 'historical_brasileirao']:
            df = self.data_loader.get_data(key)
            if df is not None:
                if 'home_team' in df.columns:
                    teams.update(df['home_team'].dropna().unique())
                if 'away_team' in df.columns:
                    teams.update(df['away_team'].dropna().unique())
                if 'home' in df.columns:
                    teams.update(df['home'].dropna().unique())
                if 'away' in df.columns:
                    teams.update(df['away'].dropna().unique())
        
        return sorted(list(teams))
    
    def get_team_by_state(self, state: str) -> List[str]:
        """
        Get teams from a specific state.
        
        Args:
            state: State abbreviation (e.g., SP, RJ, MG)
            
        Returns:
            List of teams from the state
        """
        teams = []
        
        df = self.data_loader.get_data('brasileirao')
        if df is not None:
            state_teams = df[
                (df['home_team_state'] == state) | 
                (df['away_team_state'] == state)
            ]
            teams = list(state_teams['home_team'].unique()) + list(state_teams['away_team'].unique())
        
        return sorted(list(set(teams)))


