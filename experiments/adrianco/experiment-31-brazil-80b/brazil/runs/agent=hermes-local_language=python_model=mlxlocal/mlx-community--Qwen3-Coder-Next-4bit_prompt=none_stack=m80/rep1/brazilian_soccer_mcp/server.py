@app.route('/query', methods=['POST'])
def execute_query():
    """Execute a soccer query from natural language."""
    handlers = get_handlers()
    data = request.get_json()
    
    if not data:
        return jsonify({'error': 'No query data provided'}), 400
    
    query_type = data.get('type', '')
    query = data.get('query', '')
    
    try:
        if query_type == 'match' or query_type == 'find_match':
            # Find matches
            team = data.get('team', '')
            competition = data.get('competition', '')
            season = data.get('season')
            
            if team:
                matches = handlers['match_handler'].find_matches_by_team(
                    team, 
                    competition=competition,
                    season=season if season else None
                )
                result = matches.head(20).to_dict('records')
            else:
                result = handlers['match_handler'].all_matches.head(20).to_dict('records')
            
            return jsonify({
                'type': 'matches',
                'count': len(result),
                'results': result
            })
        
        elif query_type == 'head_to_head':
            team1 = data.get('team1', '')
            team2 = data.get('team2', '')
            
            if team1 and team2:
                h2h = handlers['team_handler'].get_head_to_head(team1, team2)
                return jsonify({
                    'type': 'head_to_head',
                    'data': h2h
                })
        
        elif query_type == 'team_stats':
            team = data.get('team', '')
            season = data.get('season')
            
            if team:
                stats = handlers['team_handler'].get_team_statistics(
                    team, 
                    season=season
                )
                return jsonify({
                    'type': 'team_statistics',
                    'data': stats
                })
        
        elif query_type == 'player':
            name = data.get('name', '')
            
            if name:
                player = handlers['player_handler'].get_player_by_name(name)
                if player:
                    return jsonify({
                        'type': 'player',
                        'data': player
                    })
                else:
                    return jsonify({'error': f'Player "{name}" not found'}), 404
        
        elif query_type == 'standings':
            season = data.get('season')
            competition = data.get('competition', 'Brasileirão')
            
            if season:
                standings = handlers['competition_handler'].calculate_standings(
                    season, 
                    competition
                )
                return jsonify({
                    'type': 'standings',
                    'data': standings.head(20).to_dict('records')
                })
        
        elif query_type == 'biggest_victories':
            competition = data.get('competition', '')
            limit = data.get('limit', 10)
            
            victories = handlers['competition_handler'].get_biggest_victories(
                competition, 
                limit
            )
            return jsonify({
                'type': 'biggest_victories',
                'data': victories
            })
        
        else:
            return jsonify({'error': f'Unknown query type: {query_type}'}), 400
    
    except Exception as e:
        return jsonify({'error': str(e)}), 500


