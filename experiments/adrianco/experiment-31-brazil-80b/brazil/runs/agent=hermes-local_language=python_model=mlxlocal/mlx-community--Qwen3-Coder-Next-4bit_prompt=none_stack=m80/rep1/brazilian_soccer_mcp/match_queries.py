from typing import Dict, List, Any, Optional
import pandas as pd
from datetime import datetime


class MatchQueryHandler:
    """
    Handles match-related queries for the Brazilian Soccer MCP Server.
    
    Provides methods to search and analyze match data from all available
    datasets including Brasileirão, Copa do Brasil, Libertadores, and more.
    """
    
    def __init__(self, data_loader):
        """
        Initialize the MatchQueryHandler with a data loader.
        
        Args:
            data_loader: DataLoader instance containing match data
        """
        self.data_loader = data_loader
        self.all_matches = data_loader.get_all_matches()
    
    def find_matches_by_team(
        self, 
        team_name: str, 
        competition: Optional[str] = None,
        season: Optional[int] = None,
        limit: int = 50
    ) -> pd.DataFrame:
        """
        Find all matches for a specific team.
        
        Args:
            team_name: Team name to search for
            competition: Optional competition filter
            season: Optional season filter
            limit: Maximum number of results
            
        Returns:
            DataFrame with matching matches
        """
        team_normalized = self.data_loader._normalize_team_name(team_name)
        
        # Search in home team
        mask = (
            (self.all_matches['home_team_normalized'] == team_normalized) |
            (self.all_matches['away_team_normalized'] == team_normalized)
        )
        
        if competition:
            competition_normalized = competition.lower().strip()
            mask &= (
                (self.all_matches['competition'].str.lower().str.contains(competition_normalized)) |
                (self.all_matches['competition'].str.lower() == competition_normalized)
            )
        
        if season:
            mask &= (self.all_matches['season'] == season)
        
        result = self.all_matches[mask].head(limit)
        return result
    
    def find_match_by_teams(
        self, 
        team1: str, 
        team2: str,
        limit: int = 100
    ) -> pd.DataFrame:
        """
        Find all matches between two teams (head-to-head).
        
        Args:
            team1: First team name
            team2: Second team name
            limit: Maximum number of results
            
        Returns:
            DataFrame with matching matches
        """
        team1_normalized = self.data_loader._normalize_team_name(team1)
        team2_normalized = self.data_loader._normalize_team_name(team2)
        
        mask = (
            ((self.all_matches['home_team_normalized'] == team1_normalized) & 
             (self.all_matches['away_team_normalized'] == team2_normalized)) |
            ((self.all_matches['home_team_normalized'] == team2_normalized) & 
             (self.all_matches['away_team_normalized'] == team1_normalized))
        )
        
        result = self.all_matches[mask].head(limit)
        return result
    
    def find_matches_by_date_range(
        self,
        start_date: str,
        end_date: str,
        competition: Optional[str] = None
    ) -> pd.DataFrame:
        """
        Find matches within a date range.
        
        Args:
            start_date: Start date (YYYY-MM-DD format)
            end_date: End date (YYYY-MM-DD format)
            competition: Optional competition filter
            
        Returns:
            DataFrame with matching matches
        """
        start = pd.to_datetime(start_date)
        end = pd.to_datetime(end_date)
        
        mask = (
            (self.all_matches['datetime'] >= start) &
            (self.all_matches['datetime'] <= end)
        )
        
        if competition:
            mask &= (self.all_matches['competition'] == competition)
        
        result = self.all_matches[mask]
        return result
    
    def find_matches_by_competition(
        self,
        competition: str,
        season: Optional[int] = None
    ) -> pd.DataFrame:
        """
        Find matches by competition.
        
        Args:
            competition: Competition name
            season: Optional season filter
            
        Returns:
            DataFrame with matching matches
        """
        competition_normalized = competition.lower().strip()
        
        mask = (
            (self.all_matches['competition'].str.lower().str.contains(competition_normalized)) |
            (self.all_matches['competition'].str.lower() == competition_normalized)
        )
        
        if season:
            mask &= (self.all_matches['season'] == season)
        
        result = self.all_matches[mask]
        return result
    
    def get_match_details(self, match_id: int) -> Optional[Dict[str, Any]]:
        """
        Get detailed information about a specific match.
        
        Args:
            match_id: Match index/ID
            
        Returns:
            Dictionary with match details or None if not found
        """
        if match_id < 0 or match_id >= len(self.all_matches):
            return None
        
        match = self.all_matches.iloc[match_id]
        
        return {
            'competition': match['competition'],
            'datetime': str(match['datetime']) if pd.notna(match['datetime']) else None,
            'home_team': match['home_team'],
            'away_team': match['away_team'],
            'home_goal': int(match['home_goal']) if pd.notna(match['home_goal']) else None,
            'away_goal': int(match['away_goal']) if pd.notna(match['away_goal']) else None,
            'season': int(match['season']) if pd.notna(match['season']) else None,
            'round': int(match['round']) if 'round' in match.index and pd.notna(match['round']) else None,
            'stage': match.get('stage', None)
        }
    
    def get_match_result(self, team1: str, team2: str, date: Optional[str] = None) -> Optional[Dict[str, Any]]:
        """
        Get the result of a match between two teams.
        
        Args:
            team1: First team
            team2: Second team
            date: Optional specific date to find exact match
            
        Returns:
            Dictionary with match result or None if not found
        """
        matches = self.find_match_by_teams(team1, team2, limit=1)
        
        if len(matches) == 0:
            return None
        
        match = matches.iloc[0]
        
        home_team = match['home_team']
        away_team = match['away_team']
        home_goal = int(match['home_goal']) if pd.notna(match['home_goal']) else 0
        away_goal = int(match['away_goal']) if pd.notna(match['away_goal']) else 0
        
        if home_team == team1:
            team1_score = home_goal
            team2_score = away_goal
        else:
            team1_score = away_goal
            team2_score = home_goal
        
        if team1_score > team2_score:
            result = f"{team1} wins"
        elif team1_score < team2_score:
            result = f"{team2} wins"
        else:
            result = "Draw"
        
        return {
            'home_team': home_team,
            'away_team': away_team,
            'home_goal': home_goal,
            'away_goal': away_goal,
            'result': result,
            'datetime': str(match['datetime']) if pd.notna(match['datetime']) else None,
            'competition': match['competition'],
            'season': int(match['season']) if pd.notna(match['season']) else None
        }
    
    def get_recent_matches(self, team_name: str, limit: int = 10) -> pd.DataFrame:
        """
        Get recent matches for a team.
        
        Args:
            team_name: Team name
            limit: Number of recent matches to return
            
        Returns:
            DataFrame with recent matches
        """
        matches = self.find_matches_by_team(team_name, limit=limit * 10)
        
        if len(matches) == 0:
            return matches
        
        # Sort by date descending
        matches = matches.sort_values('datetime', ascending=False)
        
        return matches.head(limit)
    
    def get_matches_by_season(self, season: int, competition: Optional[str] = None) -> pd.DataFrame:
        """
        Get all matches for a specific season.
        
        Args:
            season: Season year
            competition: Optional competition filter
            
        Returns:
            DataFrame with matches from the season
        """
        mask = (self.all_matches['season'] == season)
        
        if competition:
            mask &= (self.all_matches['competition'].str.lower().str.contains(competition.lower()))
        
        return self.all_matches[mask]
    
    def get_competition_seasons(self, competition: str) -> List[int]:
        """
        Get all seasons that have been played in a competition.
        
        Args:
            competition: Competition name
            
        Returns:
            List of season years
        """
        competition_mask = (
            (self.all_matches['competition'].str.lower().str.contains(competition.lower())) |
            (self.all_matches['competition'].str.lower() == competition.lower())
        )
        
        seasons = self.all_matches[competition_mask]['season'].unique()
        return sorted([int(s) for s in seasons if pd.notna(s)])
    
    def analyze_match_outcome(self, match_id: int) -> Optional[Dict[str, Any]]:
        """
        Analyze the outcome of a match.
        
        Args:
            match_id: Match index/ID
            
        Returns:
            Dictionary with match analysis
        """
        match = self.get_match_details(match_id)
        if not match:
            return None
        
        home_goal = match['home_goal']
        away_goal = match['away_goal']
        
        if home_goal is None or away_goal is None:
            return None
        
        if home_goal > away_goal:
            winner = match['home_team']
            loser = match['away_team']
            score_diff = home_goal - away_goal
        elif away_goal > home_goal:
            winner = match['away_team']
            loser = match['home_team']
            score_diff = away_goal - home_goal
        else:
            winner = None
            loser = None
            score_diff = 0
        
        return {
            'winner': winner,
            'loser': loser,
            'draw': winner is None,
            'score': f"{match['home_goal']}-{match['away_goal']}",
            'score_difference': score_diff
        }


