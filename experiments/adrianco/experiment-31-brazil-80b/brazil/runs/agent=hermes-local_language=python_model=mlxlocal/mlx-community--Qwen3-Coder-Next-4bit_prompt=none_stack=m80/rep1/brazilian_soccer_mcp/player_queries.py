from typing import Dict, List, Any, Optional
import pandas as pd


class PlayerQueryHandler:
    """
    Handles player-related queries for the Brazilian Soccer MCP Server.
    
    Provides methods to search and filter player data from the FIFA database,
    including filtering by nationality, club, position, and ratings.
    """
    
    def __init__(self, data_loader):
        """
        Initialize the PlayerQueryHandler.
        
        Args:
            data_loader: DataLoader instance
        """
        self.data_loader = data_loader
        self.players_df = data_loader.get_data('fifa_players')
        
        if self.players_df is None:
            raise ValueError("FIFA player data not loaded")
    
    def search_players_by_name(self, name: str, limit: int = 20) -> pd.DataFrame:
        """
        Search players by name.
        
        Args:
            name: Player name or partial name to search for
            limit: Maximum number of results
            
        Returns:
            DataFrame with matching players
        """
        mask = self.players_df['Name'].str.contains(name, case=False, na=False)
        result = self.players_df[mask].head(limit)
        return result
    
    def get_player_by_name(self, name: str) -> Optional[Dict[str, Any]]:
        """
        Get detailed information about a specific player.
        
        Args:
            name: Exact or partial player name
            
        Returns:
            Dictionary with player details or None if not found
        """
        players = self.search_players_by_name(name, limit=1)
        
        if len(players) == 0:
            return None
        
        player = players.iloc[0]
        
        return {
            'id': int(player['ID']) if pd.notna(player['ID']) else None,
            'name': player['Name'],
            'age': int(player['Age']) if pd.notna(player['Age']) else None,
            'nationality': player.get('Nationality', 'N/A'),
            'overall': int(player['Overall']) if pd.notna(player['Overall']) else None,
            'potential': int(player['Potential']) if pd.notna(player['Potential']) else None,
            'club': player.get('Club', 'N/A'),
            'position': player.get('Position', 'N/A'),
            'jersey_number': int(player['Jersey Number']) if pd.notna(player.get('Jersey Number')) else None,
            'height': player.get('Height', 'N/A'),
            'weight': player.get('Weight', 'N/A'),
            'preferred_foot': player.get('Preferred Foot', 'N/A'),
            'international_reputation': int(player['International Reputation']) if pd.notna(player.get('International Reputation')) else None,
            'weak_foot': int(player['Weak Foot']) if pd.notna(player.get('Weak Foot')) else None,
            'skill_moves': int(player['Skill Moves']) if pd.notna(player.get('Skill Moves')) else None,
            'work_rate': player.get('Work Rate', 'N/A'),
            'value': player.get('Value', 'N/A'),
            'wage': player.get('Wage', 'N/A')
        }
    
    def search_players_by_nationality(
        self, 
        nationality: str,
        limit: int = 50
    ) -> pd.DataFrame:
        """
        Search players by nationality.
        
        Args:
            nationality: Country name to search for
            limit: Maximum number of results
            
        Returns:
            DataFrame with matching players
        """
        mask = self.players_df['Nationality'].str.contains(nationality, case=False, na=False)
        result = self.players_df[mask].head(limit)
        return result
    
    def get_brazilian_players(self, limit: int = 100) -> pd.DataFrame:
        """
        Get all Brazilian players.
        
        Args:
            limit: Maximum number of results
            
        Returns:
            DataFrame with Brazilian players
        """
        mask = (
            (self.players_df['Nationality'].str.contains('Brazil', case=False, na=False)) |
            (self.players_df['Nationality'].str.contains('Brasil', case=False, na=False))
        )
        result = self.players_df[mask].head(limit)
        return result
    
    def search_players_by_club(
        self,
        club_name: str,
        limit: int = 50
    ) -> pd.DataFrame:
        """
        Search players by club.
        
        Args:
            club_name: Club name to search for
            limit: Maximum number of results
            
        Returns:
            DataFrame with matching players
        """
        mask = self.players_df['Club'].str.contains(club_name, case=False, na=False)
        result = self.players_df[mask].head(limit)
        return result
    
    def get_players_by_position(
        self,
        position: str,
        limit: int = 50
    ) -> pd.DataFrame:
        """
        Search players by position.
        
        Args:
            position: Position to search for (e.g., 'LW', 'CDM', 'GK')
            limit: Maximum number of results
            
        Returns:
            DataFrame with matching players
        """
        mask = self.players_df['Position'].str.contains(position, case=False, na=False)
        result = self.players_df[mask].head(limit)
        return result
    
    def get_top_rated_players(self, limit: int = 10, min_overall: int = 80) -> pd.DataFrame:
        """
        Get top-rated players.
        
        Args:
            limit: Maximum number of results
            min_overall: Minimum overall rating
            
        Returns:
            DataFrame with top-rated players
        """
        mask = self.players_df['Overall'] >= min_overall
        result = self.players_df[mask].nlargest(limit, 'Overall')
        return result
    
    def get_brazilian_top_rated(self, limit: int = 20) -> List[Dict[str, Any]]:
        """
        Get top-rated Brazilian players.
        
        Args:
            limit: Number of players to return
            
        Returns:
            List of top Brazilian players with details
        """
        brazilian = self.get_brazilian_players(limit=1000)
        
        if len(brazilian) == 0:
            return []
        
        top_brazilian = brazilian.nlargest(limit, 'Overall')
        
        result = []
        for _, player in top_brazilian.iterrows():
            result.append({
                'name': player['Name'],
                'age': int(player['Age']) if pd.notna(player['Age']) else None,
                'nationality': player.get('Nationality', 'N/A'),
                'overall': int(player['Overall']) if pd.notna(player['Overall']) else None,
                'potential': int(player['Potential']) if pd.notna(player['Potential']) else None,
                'club': player.get('Club', 'N/A'),
                'position': player.get('Position', 'N/A')
            })
        
        return result
    
    def get_players_by_club_in_brazil(
        self,
        club_name: str,
        limit: int = 50
    ) -> pd.DataFrame:
        """
        Get players for a Brazilian club.
        
        Args:
            club_name: Brazilian club name
            limit: Maximum number of results
            
        Returns:
            DataFrame with club players
        """
        # Search for the club in the database
        players = self.search_players_by_club(club_name, limit=limit)
        
        # Filter to only Brazilian clubs
        brazilian_clubs = [
            'Flamengo', 'Palmeiras', 'São Paulo', 'Corinthians', 
            'Santos', 'Grêmio', 'Internacional', 'Botafogo',
            'Fluminense', 'Vasco da Gama', 'Atlético Mineiro',
            ' Cruzeiro', 'Bahia', 'Fortaleza', 'Cruzeiro',
            'Coritiba', 'Goiás', 'Sport', 'Náutico'
        ]
        
        # If players DataFrame has Club column, filter for Brazilian clubs
        if 'Club' in players.columns:
            for club in brazilian_clubs:
                if club_name.lower() in club.lower() or club.lower() in club_name.lower():
                    mask = players['Club'].str.contains(club, case=False, na=False)
                    players = players[mask]
                    break
        
        return players
    
    def get_brazilian_players_by_club(self, limit: int = 50) -> Dict[str, List[Dict[str, Any]]]:
        """
        Get Brazilian players grouped by Brazilian club.
        
        Args:
            limit: Maximum players per club
            
        Returns:
            Dictionary mapping club names to lists of players
        """
        brazilian_clubs = [
            'Flamengo', 'Palmeiras', 'São Paulo', 'Corinthians', 
            'Santos', 'Grêmio', 'Internacional', 'Botafogo',
            'Fluminense', 'Vasco da Gama', 'Atlético Mineiro',
            'Cruzeiro', 'Bahia', 'Fortaleza', 'Coritiba', 
            'Goiás', 'Sport', 'Náutico'
        ]
        
        result = {}
        
        for club in brazilian_clubs:
            players = self.search_players_by_club(club, limit=limit)
            
            club_players = []
            for _, player in players.iterrows():
                club_players.append({
                    'name': player['Name'],
                    'age': int(player['Age']) if pd.notna(player['Age']) else None,
                    'nationality': player.get('Nationality', 'N/A'),
                    'overall': int(player['Overall']) if pd.notna(player['Overall']) else None,
                    'position': player.get('Position', 'N/A')
                })
            
            if club_players:
                result[club] = club_players
        
        return result
    
    def get_player_attributes(self, player_name: str) -> Optional[Dict[str, Any]]:
        """
        Get detailed attributes for a player.
        
        Args:
            player_name: Player name
            
        Returns:
            Dictionary with player attributes or None if not found
        """
        player = self.get_player_by_name(player_name)
        
        if player is None:
            return None
        
        # Get skill attributes if available
        skill_attrs = {}
        for col in self.players_df.columns:
            if any(keyword in col.lower() for keyword in ['crossing', 'finishing', 'dribbling', 
                                                           'ballcontrol', 'passing', 'shooting',
                                                           'speed', 'strength', 'jumping', 'stamina']):
                skill_attrs[col] = player.get(col, 'N/A')
        
        return {
            'basic_info': player,
            'skill_attributes': skill_attrs
        }
    
    def get_players_by_overall_range(
        self,
        min_overall: int,
        max_overall: int,
        nationality: Optional[str] = None
    ) -> pd.DataFrame:
        """
        Get players within an overall rating range.
        
        Args:
            min_overall: Minimum overall rating
            max_overall: Maximum overall rating
            nationality: Optional nationality filter
            
        Returns:
            DataFrame with matching players
        """
        mask = (
            (self.players_df['Overall'] >= min_overall) &
            (self.players_df['Overall'] <= max_overall)
        )
        
        if nationality:
            mask &= self.players_df['Nationality'].str.contains(nationality, case=False, na=False)
        
        result = self.players_df[mask]
        return result
    
    def get_average_ratings_by_position(self) -> pd.DataFrame:
        """
        Get average ratings by position.
        
        Returns:
            DataFrame with average ratings by position
        """
        position_stats = self.players_df.groupby('Position')['Overall'].agg(['mean', 'count', 'std'])
        position_stats = position_stats.sort_values('mean', ascending=False)
        return position_stats


